def render_design_system(current: str, tokens: dict) -> str:
    if BEGIN not in current or END not in current:
        raise SystemExit(f"{DS_CSS}: marker comments {BEGIN} / {END} not found")
    a = current.index(BEGIN)
    b = current.index(END) + len(END)
    out = current[:a] + console_block(tokens) + current[b:]
    if C_BEGIN in out and C_END in out:
        table, _ = contrast_report(tokens)
        a = out.index(C_BEGIN)
        a = out.index("\n", a) + 1
        b = out.rindex("\n", 0, out.index(C_END)) + 1
        out = out[:a] + "".join(f"   {ln}".rstrip() + "\n" for ln in table) + out[b:]
    return out


def outputs(tokens: dict) -> dict[Path, str]:
    cur = DS_CSS.read_text(encoding="utf-8")
    return {
        DS_CSS: render_design_system(cur, tokens),
        CDF_CSS: cdf_css(tokens),
        CDF_TS: cdf_ts(tokens),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if an output is out of date or a contrast floor fails")
    ap.add_argument("--contrast", action="store_true", help="print the contrast table")
    a = ap.parse_args(argv)
    tokens = load()
    table, fails = contrast_report(tokens)
    if a.contrast:
        print("\n".join(table))
    stale = []
    for path, text in outputs(tokens).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not a.check:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(REPO)}")
    for f in fails:
        print(f"contrast FAIL: {f}", file=sys.stderr)
    if a.check:
        for p in stale:
            print(f"out of date: {p.relative_to(REPO)} (run python3 shared/ui-tokens/build.py)",
                  file=sys.stderr)
        return 1 if (stale or fails) else 0
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
