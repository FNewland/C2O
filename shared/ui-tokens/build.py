#!/usr/bin/env python3
"""Generate the C2O token outputs from c2o.tokens.json (stdlib only).

    python3 shared/ui-tokens/build.py           # write every output
    python3 shared/ui-tokens/build.py --check   # exit 1 if any output is stale
                                                # or a contrast floor is missed

Outputs (see README.md):
  * sim/packages/smo-common/src/smo_common/ui/design-system.css
      - the block between ``/* tokens:begin */`` and ``/* tokens:end */``
      - the contrast table in the header between the ``contrast:begin`` and
        ``contrast:end`` lines
      The rest of that file is hand-written and never touched.
  * design/frontend/src/theme/tokens.css   (whole file)
  * design/frontend/src/theme/tokens.ts    (whole file)

The consoles are dark by default (``:root``) with ``[data-theme="light"]``;
SpaceCDF is light by default with ``[data-theme="dark"]``. Both come from the
same two theme objects in the JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SRC = HERE / "c2o.tokens.json"
DS_CSS = REPO / "sim/packages/smo-common/src/smo_common/ui/design-system.css"
CDF_CSS = REPO / "design/frontend/src/theme/tokens.css"
CDF_TS = REPO / "design/frontend/src/theme/tokens.ts"

BEGIN, END = "/* tokens:begin */", "/* tokens:end */"
C_BEGIN, C_END = "contrast:begin", "contrast:end"
GEN_NOTE = "Generated by shared/ui-tokens/build.py from c2o.tokens.json. Do not edit by hand."


# ── token access ────────────────────────────────────────────────────────

def load(path: Path = SRC) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def get(tree: dict, dotted: str) -> dict:
    node = tree
    for part in dotted.split("."):
        node = node[part]
    if not isinstance(node, dict) or "$value" not in node:
        raise KeyError(f"{dotted} is not a token")
    return node


def css_value(token: dict) -> str:
    v = token["$value"]
    if isinstance(v, list) and v and isinstance(v[0], str):          # fontFamily
        return ", ".join(f"'{f}'" if (" " in f and not f.startswith("-")) else f for f in v)
    if isinstance(v, list):                                         # cubicBezier
        return "cubic-bezier(" + ", ".join(f"{x:g}" for x in v) + ")"
    return str(v)


# ── contrast (WCAG 2.2, same maths as sim/tools/check_contrast.py) ─────

def _lum(hexstr: str) -> float:
    h = hexstr.lstrip("#")
    def f(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (f(int(h[i:i + 2], 16)) for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a: str, b: str) -> float:
    la, lb = _lum(a), _lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def contrast_report(tokens: dict) -> tuple[list[str], list[str]]:
    """(table lines, failures)."""
    spec = tokens["$extensions"]["org.c2o.contrast"]
    lines: list[str] = []
    fails: list[str] = []
    for theme in ("dark", "light"):
        t = tokens["theme"][theme]
        s = spec[theme]
        surf = [(p, get(t, p)["$value"]) for p in s["surfaces"]]
        floor = s["textFloor"]
        lines.append(f"{theme.upper()} (text floor {floor:g}:1 on {' and '.join(p for p, _ in surf[:s['primary']])};"
                     f" graphics 3:1)")
        lines.append("  token            hex      " + " ".join(f"{p:>9}" for p, _ in surf))
        for group, fl in (("text", floor), ("graphics", 3.0), ("disabled", None)):
            for p in s[group]:
                hx = get(t, p)["$value"]
                rr = [ratio(hx, sv) for _, sv in surf]
                checked = rr[:s["primary"]] if group == "text" else rr[:s["primary"]]
                if fl is None:
                    verdict = "info (40 % treatment)"
                elif all(x >= fl for x in checked):
                    verdict = "PASS" if group == "text" else "PASS graphics-only"
                else:
                    verdict = "FAIL"
                    fails.append(f"{theme} {p} {hx}: {min(checked):.2f} < {fl:g}")
                lines.append(f"  {p:<16} {hx:<8} " + " ".join(f"{x:9.2f}" for x in rr) + f"  {verdict}")
        for fg, bg in spec.get("onFill", []):
            r = ratio(get(t, fg)["$value"], get(t, bg)["$value"])
            ok = r >= floor
            if not ok:
                fails.append(f"{theme} {fg} on {bg}: {r:.2f} < {floor:g}")
            lines.append(f"  {fg} on {bg}: {r:.2f}  {'PASS' if ok else 'FAIL'}")
        for fg, bg, fl in spec.get("pairs", []):
            r = ratio(get(t, fg)["$value"], get(t, bg)["$value"])
            if r < fl:
                fails.append(f"{theme} {fg} on {bg}: {r:.2f} < {fl:g}")
            lines.append(f"  {fg} on {bg}: {r:.2f}  {'PASS' if r >= fl else 'FAIL'} (graphics)")
        lines.append("")
    return lines[:-1], fails


# ── emitters ────────────────────────────────────────────────────────────

def _decls(tokens: dict, mapping: dict, tree: dict, indent: str = "  ") -> list[str]:
    out = []
    for path, names in mapping.items():
        if isinstance(names, dict):
            names = [names["css"]]
        val = css_value(get(tree, path))
        out.extend(f"{indent}{n}: {val};" for n in names)
    return out


def console_block(tokens: dict) -> str:
    m = tokens["$extensions"]["org.c2o.outputs"]["console"]
    dark, light = tokens["theme"]["dark"], tokens["theme"]["light"]
    L = [BEGIN, f"/* {GEN_NOTE} */", ":root{", "  color-scheme: dark;"]
    L += _decls(tokens, m["scale"], tokens)
    L += _decls(tokens, m["theme"], dark)
    L += ["  --hatch: repeating-linear-gradient(45deg, transparent 0 4px, var(--hatch-ink) 4px 8px);",
          "  --focus: 0 0 0 2px var(--bg), 0 0 0 4px var(--accent);", "}",
          ':root[data-theme="light"]{', "  color-scheme: light;"]
    L += _decls(tokens, m["theme"], light)
    L += ["  --hatch: repeating-linear-gradient(45deg, transparent 0 3px, var(--hatch-ink) 3px 6px);", "}", END]
    return "\n".join(L)


def cdf_css(tokens: dict) -> str:
    m = tokens["$extensions"]["org.c2o.outputs"]["cdf"]
    dark, light = tokens["theme"]["dark"], tokens["theme"]["light"]
    L = [
        "/*",
        " * C2O design tokens for SpaceCDF (docs/ui/C2O_UI_BRIEF.md §2–3, R3 §4.2).",
        f" * {GEN_NOTE}",
        " *",
        " * One token set, two themes. SpaceCDF is design work, so it defaults to the",
        " * light theme; [data-theme=\"dark\"] gives the control-room ramp used by the",
        " * SMO consoles. Components use the semantic names only (no hex in TSX).",
        " * src/theme/tokens.ts mirrors the names for inline styles.",
        " */",
        "@import '@fontsource/ibm-plex-sans/400.css';",
        "@import '@fontsource/ibm-plex-sans/400-italic.css';",
        "@import '@fontsource/ibm-plex-sans/500.css';",
        "@import '@fontsource/ibm-plex-sans/600.css';",
        "@import '@fontsource/ibm-plex-mono/400.css';",
        "@import '@fontsource/ibm-plex-mono/500.css';",
        "",
        ":root {",
        "  /* Type: 12 / 13 / 15 / 20 px, 12 px floor; values ≥ 14 px (brief §3). */",
    ]
    L += _decls(tokens, m["scale"], tokens)
    L += ["", "  /* ── Light theme (default for SpaceCDF) ── */", "  color-scheme: light;"]
    L += _decls(tokens, m["theme"], light)
    L += ["  --focus-ring: 0 0 0 2px var(--surface-1), 0 0 0 4px var(--interactive);", "}", "",
          ":root[data-theme='dark'] {", "  color-scheme: dark;"]
    L += _decls(tokens, m["theme"], dark)
    L += ["}", "",
          "/* Legacy names (index.css v1) kept as aliases so existing var() uses follow the theme. */",
          ":root {",
          "  --bg-primary: var(--surface-0);",
          "  --bg-secondary: var(--surface-1);",
          "  --bg-card: var(--surface-2);",
          "  --border: var(--line);",
          "  --text-primary: var(--text);",
          "  --text-secondary: var(--text-2);",
          "  --accent: var(--interactive);",
          "  --success: var(--status-ok);",
          "  --warning: var(--status-caution);",
          "  --danger: var(--status-alarm);",
          "  --info: var(--interactive);",
          "}", ""]
    return "\n".join(L)


def cdf_ts(tokens: dict) -> str:
    m = tokens["$extensions"]["org.c2o.outputs"]["cdf"]["theme"]
    c_lines = [f"  {v['ts']}: 'var({v['css']})'," for v in m.values() if isinstance(v, dict) and v.get("ts")]
    return TS_TEMPLATE.replace("__GEN__", GEN_NOTE).replace("__C__", "\n".join(c_lines))


