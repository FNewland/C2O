#!/usr/bin/env python3
"""Copy the shared pictorial-display modules to the apps that serve them.

    python3 shared/ui-viz/sync.py           # write every copy
    python3 shared/ui-viz/sync.py --check   # exit 1 if any copy is stale,
                                            # missing, or has an extra file

``shared/ui-viz/`` is the single source of truth for the framework-free ES
modules that draw C2O's pictorial displays (derive.js, powerflow.js,
overview.js, attitude2d.js, attitude3d.js, groundtrack.js, skyplot.js, the
vendored three.js under vendor/). Two apps import them:

  * the SMO consoles  -> sim/packages/smo-common/src/smo_common/ui/viz/
                         (served by every SMO server at /static/shared/viz/)
  * SpaceCDF          -> design/frontend/src/viz/

The copies are byte-identical and GENERATED: never edit them. Edit the file
here, run this script, commit both. ``sim/tests/test_common/test_ui_viz.py``
runs ``--check`` so a hand edit or a forgotten sync fails the suite (same
contract as shared/ui-tokens/build.py). Stdlib only.
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
TARGETS = (
    REPO / "sim/packages/smo-common/src/smo_common/ui/viz",
    REPO / "design/frontend/src/viz",
)
# What is shipped: the modules, their demo page and the vendored libraries
# (with their licences). The tooling and its notes stay here.
SHIP_SUFFIXES = {".js", ".mjs", ".css", ".html", ".json", ".svg", ".txt", ".d.ts"}
SHIP_NAMES = {"LICENSE", "LICENSE.md", "LICENSE.txt"}
SKIP_NAMES = {"sync.py", "README.md"}
SKIP_DIRS = {"__pycache__", "tests", "node_modules", ".git"}
MARKER = "GENERATED.txt"
MARKER_TEXT = (
    "Generated by shared/ui-viz/sync.py from shared/ui-viz/. Do not edit:\n"
    "edit the source there and run `python3 shared/ui-viz/sync.py`.\n"
    "sim/tests/test_common/test_ui_viz.py fails if this copy drifts.\n"
)


def shipped() -> dict[str, bytes]:
    """{relative posix path: bytes} for every file that is copied."""
    out: dict[str, bytes] = {}
    for p in sorted(HERE.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(HERE)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if rel.as_posix() in SKIP_NAMES or p.name == MARKER:
            continue
        if p.suffix in SHIP_SUFFIXES or p.name in SHIP_NAMES:
            out[rel.as_posix()] = p.read_bytes()
    out[MARKER] = MARKER_TEXT.encode("utf-8")
    return out


def existing(target: Path) -> dict[str, bytes]:
    if not target.exists():
        return {}
    return {p.relative_to(target).as_posix(): p.read_bytes()
            for p in sorted(target.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts}


def diff(target: Path, want: dict[str, bytes]) -> list[str]:
    have = existing(target)
    probs = []
    for rel, data in want.items():
        if rel not in have:
            probs.append(f"missing  {target / rel}")
        elif have[rel] != data:
            probs.append(f"stale    {target / rel}")
    for rel in have:
        if rel not in want:
            probs.append(f"extra    {target / rel}")
    return probs


def write(target: Path, want: dict[str, bytes]) -> int:
    n = 0
    have = existing(target)
    for rel in have:
        if rel not in want:
            (target / rel).unlink()
            n += 1
    for rel, data in want.items():
        dst = target / rel
        if have.get(rel) == data:
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        n += 1
    # prune directories left empty by removed files
    for d in sorted((p for p in target.rglob("*") if p.is_dir()), reverse=True):
        if not any(d.iterdir()):
            shutil.rmtree(d)
    return n


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="report stale/missing/extra copies and exit 1; write nothing")
    a = ap.parse_args(argv)
    want = shipped()
    if a.check:
        probs = [p for t in TARGETS for p in diff(t, want)]
        for p in probs:
            print(p)
        if probs:
            print(f"ui-viz: {len(probs)} problem(s); run python3 shared/ui-viz/sync.py")
            return 1
        print(f"ui-viz: {len(want)} file(s) in sync in {len(TARGETS)} target(s)")
        return 0
    for t in TARGETS:
        n = write(t, want)
        print(f"ui-viz: {t.relative_to(REPO)}: {n} file(s) written/removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
