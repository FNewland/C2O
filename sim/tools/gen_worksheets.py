#!/usr/bin/env python3
"""gen_worksheets.py — course-workbook worksheets as logbook YAML.

The participant logbook (docs/plan_2026-11/LOGBOOK_SPEC.md §4) offers the
course workbook's worksheets inside the tools, in context. Their text must
not drift from the printed workbook, so it is never hand-copied: this script
parses the OrbitNorth Week 3 workbook (English, and its French twin) and
writes ``configs/eosat1/worksheets/ops_week3.yaml``, merged with the
hand-maintained ``worksheet_map.yaml`` (which tools, procedures, pages and
scenarios each worksheet applies to). Only the worksheets named in the map
are generated.

What becomes a question (the same rules on both languages; the English
document decides, the French one is aligned item by item and must have the
same shape, or the script stops and says where):

  * a confirm-each-step table row     -> ``check`` ("3. TT&C: action"; the
                                          expected verification as ``hint``)
  * a ``| Item | ☐ |`` / criterion row -> ``check``
  * a ``| Field | Entry |`` row         -> ``text`` (a pre-filled cell or the
                                          printed choices become the hint)
  * a grid whose rows are only numbers -> one ``text`` question for the grid
  * ``**Label:** ____`` fields,
    numbered reflection questions and
    a prompt line followed by ``____``  -> ``text`` (``☐ yes ☐ no`` -> check)

Identity and signature boxes (name, date, operator, signatures) are not
questions: the logbook already knows who and when.

For the ops workbook (logbook "Workbook" tab) a confirm-each-step row
carries ``step`` (its printed number), so the live checklist can line it up
with the procedure card; the map's ``form`` / ``instances`` / ``prefill``
(see worksheet_map.yaml) are copied onto the sheet and its questions.

Usage::

    python3 tools/gen_worksheets.py            # write ops_week3.yaml
    python3 tools/gen_worksheets.py --check    # CI gate: exit 1 if stale
    python3 tools/gen_worksheets.py --output /tmp/x.yaml
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

SIM = Path(__file__).resolve().parent.parent
C2O = SIM.parent
WS_DIR = SIM / "configs" / "eosat1" / "worksheets"
MAP_FILE = WS_DIR / "worksheet_map.yaml"
OUT_FILE = WS_DIR / "ops_week3.yaml"

HEADER = """\
# GENERATED FILE — DO NOT EDIT BY HAND.
# Generated by tools/gen_worksheets.py from the course workbook (source,
# source_fr below) and worksheet_map.yaml. Edit those, then re-run:
#     python3 tools/gen_worksheets.py
"""

# ── markdown model ──────────────────────────────────────────────────────

_WS_HEAD = re.compile(r"^# (?:Worksheet|Fiche) (WB-[0-9A-Za-z.\-]+) — (.+?)\s*$")
_APPX_HEAD = re.compile(r"^# (?:Appendix|Annexe) (WB-[A-Z])\b")
_APPX_SUB = re.compile(r"^## (CTG-\d{3}|NOM-\d{3}|LEOP-\d{3}|COM-\d{3}|EMG-\d{3}) (.+?)\s*$")
_ANY_H1 = re.compile(r"^# ")
_SECTION = re.compile(r"^#{2,4} (.+?)\s*$")
_BLANKS = re.compile(r"_{3,}")
_NUM = re.compile(r"^(\d+[a-z]?)\.\s+(.*)$")
_BOLD = re.compile(r"\*\*(.+?)\*\*")
_BOX = "☐"


def _clean(s: str) -> str:
    """Plain text: no emphasis markers, code ticks, maths dollars or blanks."""
    s = s.replace("\\|", "|")
    s = _BLANKS.sub(" ", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"\1", s)
    s = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", s)
    # inline maths ($SoC_{exit} = ... \cdot t$) as plain text
    s = re.sub(r"\$([^$]+)\$", lambda m: re.sub(r"_\{([^}]*)\}", r"_\1", m.group(1))
               .replace("\\cdot", "·").replace("\\times", "×"), s)
    s = s.replace("`", "").replace("$", "")
    s = re.sub(r"\s+", " ", s).strip()
    return s.strip(" :").strip()


def _only_blanks(s: str) -> bool:
    """A line that is only write-in blanks (units such as "%" or "s" allowed)."""
    return bool(_BLANKS.search(s)) and len(re.sub(r"[_\s,:/()%°\-+.]", "", s)) <= 3


def _cells(line: str) -> list[str]:
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    parts = re.split(r"(?<!\\)\|", body)
    return [p.strip() for p in parts]


def _fields_in(line: str) -> list[tuple[str, str]]:
    """``**Label:** value`` pairs on one line (value up to the next label)."""
    out = []
    ms = list(_BOLD.finditer(line))
    for i, m in enumerate(ms):
        label = m.group(1).strip()
        end = ms[i + 1].start() if i + 1 < len(ms) else len(line)
        value = line[m.end():end].strip()
        is_blank = (not _clean(value) or _BLANKS.search(value) or _BOX in value)
        if (label.endswith(":") or value.startswith(":")) and is_blank:
            out.append((label.rstrip(" :").strip(), value.lstrip(": ").strip()))
    return out


def parse_workbook(text: str) -> dict[str, dict]:
    """``{worksheet id: {"title": str, "items": [...]}}`` in document order.

    Items: ("section", heading) · ("table", header, rows) ·
    ("field", label, value) · ("prompt", text).
    """
    sheets: dict[str, dict] = {}
    cur: dict | None = None
    appendix: str | None = None
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m = _WS_HEAD.match(line)
        if m:
            appendix = None
            cur = sheets.setdefault(m.group(1), {"title": _clean(m.group(2)), "items": []})
            i += 1
            continue
        m = _APPX_HEAD.match(line)
        if m:
            appendix, cur = m.group(1), None
            i += 1
            continue
        if _ANY_H1.match(line):
            cur, appendix = None, None
            i += 1
            continue
        if appendix:
            m = _APPX_SUB.match(line)
            if m:
                wid = f"{appendix}-{m.group(1)}"
                cur = sheets.setdefault(wid, {"title": _clean(f"{m.group(1)} {m.group(2)}"),
                                              "items": []})
                i += 1
                continue
        if cur is None:
            i += 1
            continue
        items = cur["items"]
        stripped = line.strip()
        if not stripped or stripped == "---":
            i += 1
            continue
        m = _SECTION.match(line)
        if m:
            items.append(("section", _clean(m.group(1))))
            i += 1
            continue
        if stripped.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_cells(lines[i]))
                i += 1
            header, body = rows[0], [r for r in rows[1:]
                                     if not all(re.fullmatch(r":?-+:?", c or "-") for c in r)]
            items.append(("table", header, body))
            continue
        # bullet / plain field lines
        bullet = re.match(r"^\s*[-*]\s+(.*)$", line)
        content = bullet.group(1) if bullet else stripped
        fields = _fields_in(content)
        if fields:
            i += 1
            if len(fields) == 1 and not fields[0][1].strip():
                # "**Label:**" alone: a prompt when write-in lines follow,
                # otherwise a heading over a list (nothing to answer).
                # ("**Label:** ____" with its blank on the same line is a
                # field, handled below.)
                j = i
                while j < len(lines) and not lines[j].strip():
                    j += 1
                if j < len(lines) and _only_blanks(lines[j]):
                    items.append(("prompt", fields[0][0]))
                continue
            for label, value in fields:
                items.append(("field", label, value))
            continue
        if bullet:
            # "- Label: ____" (non-bold field inside a list), or a bullet
            # ending in ":" with its write-in line below.
            fm = re.match(r"^(.+?):\s*(_{3,}.*)$", content)
            i += 1
            if fm and fm.group(1).strip():
                items.append(("field", fm.group(1).strip(), fm.group(2)))
            elif content.rstrip().endswith(":") and i < len(lines) and _only_blanks(lines[i]):
                items.append(("field", content.rstrip().rstrip(":"), lines[i].strip()))
                i += 1
            continue
        m = _NUM.match(stripped)
        if m:
            parts = [m.group(2)]
            i += 1
            while i < len(lines) and lines[i].startswith("   ") and lines[i].strip() \
                    and not _only_blanks(lines[i]):
                parts.append(lines[i].strip())
                i += 1
            q = " ".join(parts)
            if _clean(q):
                items.append(("prompt", q))
            continue
        if _only_blanks(stripped):
            i += 1
            continue
        # A paragraph: a prompt when it carries blanks or a blank line follows.
        para = [stripped]
        i += 1
        while i < len(lines) and lines[i].strip() and not lines[i].strip().startswith(("|", "#", "-", "**")) \
                and not _only_blanks(lines[i]) and not _NUM.match(lines[i].strip()):
            para.append(lines[i].strip())
            i += 1
        ptext = " ".join(para)
        j = i
        while j < len(lines) and not lines[j].strip():
            j += 1
        if _BLANKS.search(ptext) or (j < len(lines) and _only_blanks(lines[j])):
            inline = re.match(r"^(.+?):?\s*_{3,}", ptext)
            items.append(("prompt", inline.group(1) if inline else ptext))
        else:
            items.append(("para", ptext))
    return sheets


# ── questions ───────────────────────────────────────────────────────────

_SKIP_FIELD = re.compile(
    r"(?i)signature|^name$|^date$|^operator|^assessor|^observer|^team$|^lead$|"
    r"^outgoing|^incoming|^time complete|^time started|^self-mark|^score|^total|"
    r"^shift end$|^handover (start|end)$|^duration$|^pass$|^pass-set$|^trigger time$|"
    r"^pass start|^pass observed$|^honours threshold$")
_SKIP_ROW = re.compile(r"(?i)signature|^fd sig$")
_STEP_HEAD = {"#", "row", "pass", "anomaly #", "elapsed"}
_YESNO = re.compile(r"☐\s*(yes|oui)\b.*☐\s*(no|non)\b", re.I)


def _choices(v: str) -> str:
    """'☐ Borealis ☐ Austral' -> 'Borealis / Austral'."""
    if _BOX not in v:
        return ""
    parts = [p.strip(" —-:") for p in v.split(_BOX)]
    return " / ".join(_clean(p) for p in parts if _clean(p))


class ShapeError(ValueError):
    pass


def _pair(en_items, fr_items, wid):
    if len(en_items) != len(fr_items) or any(a[0] != b[0] for a, b in zip(en_items, fr_items)):
        en_k = [a[0] for a in en_items]
        fr_k = [b[0] for b in fr_items]
        raise ShapeError(f"{wid}: EN and FR differ in shape\n  EN {en_k}\n  FR {fr_k}")
    return zip(en_items, fr_items)


def build_questions(wid: str, en: dict, fr: dict) -> list[dict]:
    qs: list[dict] = []
    section = None
    skip_section = False

    def add(kind, en_text, fr_text, hint=None, hint_fr=None, step=None):
        en_text, fr_text = _clean(en_text), _clean(fr_text)
        if not en_text:
            return
        q = {"id": f"q{len(qs) + 1}", "kind": kind, "text": {"en": en_text, "fr": fr_text or en_text}}
        if hint and _clean(hint):
            q["hint"] = {"en": _clean(hint), "fr": _clean(hint_fr or hint) or _clean(hint)}
        if section:
            q["section"] = dict(section)
        if step:
            # A confirm-each-step row: the logbook's live checklist lines the
            # printed row up with the procedure card's step (checklist.py).
            q["step"] = step
        qs.append(q)

    for a, b in _pair(en["items"], fr["items"], wid):
        kind = a[0]
        if kind == "section":
            # Repeated printed copies ("Ticket — copy 2") are the same form;
            # the logbook files each one as its own instance, so the first
            # copy's "— copy 1" heading is not a section either.
            skip_section = bool(re.search(r"(?i)copy [2-9]", a[1]))
            first_copy = bool(re.search(r"(?i)copy 1\b", a[1]))
            section = None if skip_section or first_copy else {"en": a[1], "fr": b[1]}
            continue
        if skip_section:
            continue
        if kind == "para":
            continue
        if kind == "prompt":
            if not _SKIP_FIELD.search(_clean(a[1])):
                add("text", a[1], b[1])
            continue
        if kind == "field":
            label, value = a[1], a[2]
            if _SKIP_FIELD.search(_clean(label)):
                continue
            if _YESNO.search(value) or (_BOX in value and not _choices(value)):
                add("check", label, b[1])
            else:
                add("text", label, b[1], _choices(value), _choices(b[2]))
            continue
        if kind == "table":
            _table_questions(wid, a, b, add)
    return qs


def _table_questions(wid, a, b, add):
    hdr_en = [_clean(c).lower() for c in a[1]]
    rows_en, rows_fr = a[2], b[2]
    if len(rows_en) != len(rows_fr) or len(a[1]) != len(b[1]):
        raise ShapeError(f"{wid}: table differs in shape between EN and FR ({a[1]})")
    box_cols = [k for k, c in enumerate(a[1]) if _BOX in c]
    first = hdr_en[0] if hdr_en else ""

    def col(*names):
        for k, h in enumerate(hdr_en):
            if any(h == n or h.startswith(n) for n in names):
                return k
        return None

    if first in _STEP_HEAD:
        action = col("action", "competency", "scenario", "criterion", "item", "check")
        if action is None:
            # A grid (Pass | Station | AOS ...) rows numbered only: one
            # question for the whole grid, the columns as the prompt.
            cols_en = " · ".join(_clean(c) for c in a[1][1:])
            cols_fr = " · ".join(_clean(c) for c in b[1][1:])
            add("text", cols_en, cols_fr,
                f"{len(rows_en)} rows", f"{len(rows_fr)} lignes")
            return
        owner = col("owner")
        expect = col("expected verification", "verification", "expected")
        for re_, rf in zip(rows_en, rows_fr):
            n = _clean(re_[0])
            parts_en = [_clean(re_[action])]
            parts_fr = [_clean(rf[action])]
            if owner is not None and _clean(re_[owner]):
                parts_en.insert(0, _clean(re_[owner]) + ":")
                parts_fr.insert(0, _clean(rf[owner]) + " :")
            prefix = f"{n}. " if n else ""
            kind = "check" if box_cols else "text"
            # Only a confirm-each-step table (an "Expected verification" or
            # "Verification" column) is a procedure step list.
            step = n if (expect is not None and n and first == "#") else None
            add(kind, prefix + " ".join(parts_en), prefix + " ".join(parts_fr),
                re_[expect] if expect is not None else None,
                rf[expect] if expect is not None else None, step=step)
        return
    # label | value tables
    kind = "check" if any(k > 0 for k in box_cols) else "text"
    for re_, rf in zip(rows_en, rows_fr):
        label = _clean(re_[0])
        if not label or _SKIP_ROW.search(label):
            continue
        hint_en = hint_fr = None
        if kind == "text" and len(re_) > 1:
            v_en, v_fr = re_[1], rf[1]
            hint_en = _choices(v_en) or (_clean(v_en) if _clean(v_en) not in ("", "/ / /") else None)
            hint_fr = _choices(v_fr) or (_clean(v_fr) if _clean(v_fr) not in ("", "/ / /") else None)
        add(kind, re_[0], rf[0], hint_en, hint_fr)


# ── output ──────────────────────────────────────────────────────────────

APPLY_KEYS = ("tools", "procedures", "pages", "scenarios", "context_keys")
PHASES = ("prep", "during", "debrief", "exercise")
#: How the logbook presents a sheet (logbook.js): a form filled and saved as
#: one record, several instances allowed for tickets and handovers.
FORMS = ("anomaly", "scorecard", "handover", "briefing", "debrief")


def _apply_prefill(wid: str, qs: list[dict], prefill: dict) -> None:
    """``prefill: {English question text: key}`` -> ``prefill: key`` on the
    question. A label that matches no question stops the script: the
    workbook was edited and the map must follow."""
    for label, key in (prefill or {}).items():
        hits = [q for q in qs if q["text"]["en"] == label
                or re.sub(r"^\d+[a-z]?\.\s+", "", q["text"]["en"]).startswith(label)]
        if not hits:
            raise SystemExit(f"{wid}: prefill label {label!r} matches no question")
        for q in hits:
            q["prefill"] = str(key)
TOOLS = ("mcs", "delayed_tm", "orbit", "radio", "docs", "instructor", "portal", "design")


def generate(map_file: Path = MAP_FILE) -> str:
    mp = yaml.safe_load(map_file.read_text(encoding="utf-8"))
    src, src_fr = mp["source"], mp["source_fr"]
    en = parse_workbook((C2O / src).read_text(encoding="utf-8"))
    fr = parse_workbook((C2O / src_fr).read_text(encoding="utf-8"))
    out = []
    for wid, spec in mp["worksheets"].items():
        if wid not in en:
            raise SystemExit(f"worksheet_map.yaml names {wid}, which is not in {src}")
        if wid not in fr:
            raise SystemExit(f"worksheet_map.yaml names {wid}, which is not in {src_fr}")
        phase = spec.get("phase")
        if phase not in PHASES:
            raise SystemExit(f"{wid}: phase must be one of {PHASES}, not {phase!r}")
        bad = [t for t in spec.get("tools", []) if t not in TOOLS]
        if bad:
            raise SystemExit(f"{wid}: unknown tools {bad}")
        qs = build_questions(wid, en[wid], fr[wid])
        if not qs:
            raise SystemExit(f"{wid}: no questions found")
        applies = {k: list(spec.get(k) or []) for k in APPLY_KEYS}
        form = spec.get("form")
        if form is not None and form not in FORMS:
            raise SystemExit(f"{wid}: form must be one of {FORMS}, not {form!r}")
        _apply_prefill(wid, qs, spec.get("prefill"))
        sheet = {
            "id": wid,
            "title": {"en": en[wid]["title"], "fr": fr[wid]["title"]},
            "phase": phase,
            "applies": applies,
        }
        if form:
            sheet["form"] = form
            if spec.get("instances"):
                sheet["instances"] = True
        sheet["questions"] = qs
        out.append(sheet)
    doc = {"source": src, "source_fr": src_fr, "worksheets": out}
    return HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True,
                                   width=100, default_flow_style=False)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed ops_week3.yaml is stale")
    ap.add_argument("--output", type=Path, default=OUT_FILE)
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != text:
            print(f"{OUT_FILE.relative_to(SIM)} is stale: re-run tools/gen_worksheets.py")
            return 1
        print("worksheets current")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
