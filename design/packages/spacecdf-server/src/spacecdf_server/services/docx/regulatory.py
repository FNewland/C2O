"""SpaceCDF Word document family: regulatory (W5.04).

``render_regulatory_docx(model)`` renders one licensing document model of
``services/licensing_docs.py`` (RSSSA, ISED space station, ISED earth station, ITU API, debris
mitigation plan, UN registration, export-control summary, licensing status). Every row says where
its value comes from: values the team still has to provide are printed as
"[APPLICANT INPUT REQUIRED: ...]", facts to be confirmed are listed at the end.

``_generate_regulatory_docx`` (registry ``/docx/{itu_api,iaru,rsssa,export,copuos,eol}``) renders a
document model when it is given one; called with the legacy ``data`` dict it gives a short document
that points to the study-linked generators (``POST /api/exports/regulatory/{kind}/{study_id}``)
instead of the old empty template.
"""
from __future__ import annotations

import io
from typing import Any

from docx import Document

from ._common import (
    _add_cover_page,
    _add_footer,
    _add_toc_placeholder,
    _render_formatted_table,
    _setup_margins,
    _setup_styles,
)

_SOURCE_NOTE = {"design": "", "team": "team input", "input": "MISSING", "tbc": "to be confirmed", "open": "open"}


def render_regulatory_docx(model: dict[str, Any]) -> bytes:
    """One licensing document model -> .docx bytes."""
    doc = Document()
    _setup_styles(doc)
    _setup_margins(doc)
    name = model.get("mission_name") or model.get("study_name") or ""
    _add_cover_page(doc, model.get("title", "Regulatory document"), model.get("standard", ""), name)
    _add_toc_placeholder(doc)
    _add_footer(doc, name, model.get("kind", "").upper())
    doc.add_paragraph(f"Authority: {model.get('authority', '')}")
    doc.add_paragraph(f"Generated by SpaceCDF from the study on {model.get('generated', '')}. Values marked "
                      f"\"team input\" come from the Licensing tab; \"[APPLICANT INPUT REQUIRED]\" marks inputs "
                      f"still missing; \"to be confirmed\" marks facts to check before filing.")
    for sec in model.get("sections") or []:
        num = str(sec.get("number", ""))
        doc.add_heading(f"{num} {sec.get('title', '')}".strip() if not num.startswith("Annex")
                        else f"{num}: {sec.get('title', '')}", level=1)
        rows = sec.get("rows") or []
        if rows:
            _render_formatted_table(doc, ["Item", "Value", "Source"],
                                    [[r["label"], r["value"], _SOURCE_NOTE.get(r.get("source", ""), r.get("source", ""))]
                                     for r in rows])
        for p in sec.get("paragraphs") or []:
            doc.add_paragraph(p)
        t = sec.get("table")
        if t and t.get("rows"):
            _render_formatted_table(doc, t["columns"], [[str(c) for c in r] for r in t["rows"]])
        elif t is not None and not rows:
            doc.add_paragraph("None listed.")
    opens = model.get("open_items") or []
    tbc = model.get("to_be_confirmed") or []
    if opens or tbc:
        doc.add_heading("Open items before filing", level=1)
        for o in opens:
            doc.add_paragraph(o, style="List Bullet")
        for t in tbc:
            doc.add_paragraph(f"To be confirmed: {t}", style="List Bullet")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _generate_regulatory_docx(study_name: str, data: dict[str, Any]) -> bytes:
    """Registry entry: a document model is rendered; the legacy data dict gives a pointer document."""
    if isinstance(data, dict) and isinstance(data.get("sections"), list):
        return render_regulatory_docx(data)
    orbit = (data or {}).get("orbit") or {}
    sid = next((e.get("study_id") for e in (data or {}).get("elements") or [] if e.get("study_id")), "{study_id}")
    model = {
        "kind": "regulatory", "title": "Regulatory filing", "mission_name": study_name,
        "standard": "Study-linked licensing documents (W5.04)", "authority": "see each document",
        "generated": "", "sections": [
            {"number": "1", "title": "Mission overview",
             "rows": [{"label": "Problem statement", "source": "design",
                       "value": ((data or {}).get("mission_need") or {}).get("problem_statement") or "not stated"}]},
            {"number": "2", "title": "Orbit",
             "rows": [{"label": k.replace("_", " "), "value": str(v), "source": "design"} for k, v in orbit.items()]},
            {"number": "3", "title": "Study-linked licensing documents", "paragraphs": [
                "The licence applications are generated from the study, with the Licensing tab's inputs:",
                *(f"POST /api/exports/regulatory/{k}/{sid}?fmt=docx" for k in
                  ("rsssa", "ised-space", "ised-earth", "itu-api", "debris", "un-registration", "export-control",
                   "status"))]},
        ]}
    return render_regulatory_docx(model)
