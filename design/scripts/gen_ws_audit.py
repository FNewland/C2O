#!/usr/bin/env python3
"""Write the worksheet ↔ screen audit and the external-link list from where_map.yaml.

    python3 scripts/gen_ws_audit.py            # (re)write the two docs/plan_2026-11 files
    python3 scripts/gen_ws_audit.py --check    # exit 1 if either is stale

Sources: configs/worksheets/where_map.yaml (hand-maintained audit), learner_workbook.yaml
(generated question text) and decision_catalogue.yaml. Outputs (repository root):

    docs/plan_2026-11/WORKSHEET_SCREEN_AUDIT_DESIGN.md
    docs/plan_2026-11/EXTERNAL_LINKS_DESIGN.md
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent          # design/
WS = ROOT / "configs" / "worksheets"
OUT_DIR = ROOT.parent / "docs" / "plan_2026-11"
AUDIT = OUT_DIR / "WORKSHEET_SCREEN_AUDIT_DESIGN.md"
LINKS = OUT_DIR / "EXTERNAL_LINKS_DESIGN.md"

STATUS_ORDER = ["screen", "screen+book", "book", "team", "ops", "partial", "gap", "deferred"]
STATUS_TEXT = {
    "screen": "answerable from SpaceCDF screens",
    "screen+book": "screens plus the open textbook / hand work",
    "book": "textbook and hand calculation only",
    "team": "team or personal work (no tool needed)",
    "ops": "answered in the ops simulator (week 3)",
    "partial": "part answerable, part not",
    "gap": "names a screen or value SpaceCDF does not have",
    "deferred": "not answerable from the tool yet (reason given)",
}

INTRO = """\
# Worksheet ↔ screen audit — SpaceCDF learner workbook (Nov 2026)

GENERATED by `design/scripts/gen_ws_audit.py` from `design/configs/worksheets/where_map.yaml`
(hand-maintained) — edit the map, then regenerate. `tests/test_logbook/test_where_map.py`
fails when this file is stale.

**Question.** Franz: "work through the worksheets with the screens to see what can be worked out
from the screens and what needs additional info — then add the additional info where needed."

**Method.** Every question of the 20 learner-workbook worksheets
(`design/docs/course/learner_workbook_expanded.md`, EN + FR, 140 questions) and every decision of
the catalogue (`decision_catalogue.yaml`, {n_dec} decisions) was checked against the running tool:
backend + built frontend, an Earth-observation study created through Mission Definition
("PrairieEye-6U", SSO 500 km, 6 kg target), Run Analysis, every activity tab at levels 0–3,
every V&V section, Export and Guide, after accepting the proposed interfaces and proposing the
electrical, data, TM/TC, FDIR, AOCS and operations models, and running every analysis.
For each question: can the student answer it from the screens (which view), only from the open
textbook *Concurrent Spacecraft Design* (`design/docs/oer`, § numbers below), or not at all?

**Status vocabulary.**

{vocab}

## Summary

| Status | Before | Now |
|---|---:|---:|
{summary}
| **Total questions** | **{n_q}** | **{n_q}** |

Questions that named a screen SpaceCDF does not have ("Design Dashboard", "Gate Review tab",
"Compliance panel", "Link Budget tab", "Equipment Browser", "ConOps Editor", "Exports tab"…):
**{n_gap_before} before, {n_gap_now} now.** Questions with at least one "Where in SpaceCDF" link:
**{n_where}**. Decisions with a "Where" link: **{n_dec_where} of {n_dec}**.

### What changed

**Screens (the screen shows or computes it).**
1. *Analyses › Design loop › key results* (new, `workbench/DesignLoopResults.tsx`): the design
   agents' orbit (semi-major axis, period, velocity, eclipse and sunlight minutes, eclipse
   fraction, node drift, sun-synchronous inclination for the altitude), power sizing (sunlit and
   eclipse loads, array EOL/BOL power and area, battery capacity and depth of discharge, power
   margin, radiator, heater), link and data (downlink rate, payload/TT&C/uplink margins, contact
   time, data per day, storage), delta-v and propulsion (deorbit, maintenance, Isp, propellant) and
   cost by element (hardware, development, launch, operations, total, shares). The loop computed
   them but no screen showed them, so Worksheets 2.3, 3.1, 3.3, 3.4 and 4.4 asked students to
   "compare with SpaceCDF" against nothing. Read-only estimates from the run's series; two rows
   derived on screen say so.
2. *Decide › Orbit Trade Study*: Rank, Period, Eclipse, Lifetime (one decimal), 25-yr and
   FCC 5-yr columns (the server already returned `compliant_5yr`, the table hid it) and a legend
   — the columns Worksheet 2.3 Part B's table asks for.
3. *Traceability › Mission need* (new, `components/MissionNeedCard.tsx`): problem statement,
   operational context, mission type, stakeholders, objectives with their measures and the
   alternative chosen with its rationale — read-only. Before, what the team typed in Mission
   Definition disappeared once the study existed, yet Worksheet 1.4 and decisions D-1.4-* return
   to it.
4. Anchors (`data-where`) on the places the links open: Decide tools, analysis cards, the Physics
   AOCS and thermal sections, Conflicts, Parameters & equations, Equipment Catalog, readiness
   checklist, Mission need.

**"Where in SpaceCDF" links.** Every worksheet question the tool helps answer ({n_where} of
{n_q}; the rest are textbook, team or ops-simulator work) and every decision in the logbook now
lists the places that answer it (`where`, generated into `learner_workbook.yaml` by
`gen_worksheets.py`; decisions resolved by `logbook/where.py`). A link switches SpaceCDF there:
Mission Definition step (before the study exists), level (drilling to the space segment,
spacecraft or the right subsystem), activity tab, the section inside it (Decide tool, analysis
card, budget, mode view, TM/TC or FDIR sub-tab, V&V section) or a toolbar dialog, then scrolls to
and highlights the anchor. The logbook stays open. The open-textbook sections and external
reading are listed with it.

**Rewordings (EN + FR, learner workbook).** {n_reworded} questions now use the screen's own
names (listed in the table with "Reworded"); the four "SpaceCDF Tabs" headers of Worksheets
2.3–3.4 and the 3.4 header name real tabs; the final-review checklist (session 5.4) points at
Budget, Modes, Analyses and Export instead of a dashboard. Question ids are unchanged, so logbook
answers keep their place.

**External links.** {n_links} open-access references, each opened and checked on {checked}
(`EXTERNAL_LINKS_DESIGN.md`). https only, on an allow-list of hosts
(`frontend/src/where/links.ts`), opened in a new window with `rel="noopener noreferrer"`;
French pages where the publisher has one.

**Deferred.** {deferred}
"""


def _md(text: str) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def load():
    wm = yaml.safe_load((WS / "where_map.yaml").read_text(encoding="utf-8"))
    wb = yaml.safe_load((WS / "learner_workbook.yaml").read_text(encoding="utf-8"))
    cat = yaml.safe_load((WS / "decision_catalogue.yaml").read_text(encoding="utf-8"))
    return wm, wb, cat


def render_audit(wm: dict, wb: dict, cat: dict) -> str:
    parts = wm.get("parts") or {}
    targets = wm.get("targets") or {}
    links = wm.get("links") or {}
    label = lambda tid: (targets.get(tid) or {}).get("label", {}).get("en", tid)   # noqa: E731
    before = Counter(p.get("before") for p in parts.values())
    now = Counter(p.get("status") for p in parts.values())
    n_q = sum(len(w["questions"]) for w in wb["worksheets"])
    summary = "\n".join(f"| {s} | {before.get(s, 0)} | {now.get(s, 0)} |" for s in STATUS_ORDER)
    vocab = "\n".join(f"- `{s}` — {STATUS_TEXT[s]}" for s in STATUS_ORDER)
    reworded = [k for k, p in parts.items() if "Reworded" in str(p.get("fix") or "")]
    deferred = [f"{k} — {_md(p.get('reason')).rstrip('.')}" for k, p in parts.items() if p.get("status") == "deferred"]
    dec_where = 0
    for d in cat["decisions"]:
        own = (wm.get("decisions") or {}).get(d["id"]) or {}
        pw = (parts.get(d.get("part") or "") or {}).get("where")
        if own.get("where") or pw:
            dec_where += 1
    checked = sorted({str(v.get("checked")) for v in links.values()})
    rev_def = [r for r in wm.get("reverse") or [] if r.get("status") == "deferred"]
    deferred_text = ("Questions: " + "; ".join(deferred) + ". " if deferred else "") + (
        f"Screens no worksheet prepares for: {len(rev_def)} (section 3). "
        "Line-by-line link budget: stays the student's own calculation in Worksheet 3.3 Part B "
        "(the tool shows the margins it computed, not every row). Found, not fixed (design agents, "
        "outside this audit): `spacecdf-agents/pyproject.toml` registers 13 agents as entry points; "
        "the debris, sustainability, conflicts, radiation, volume and reliability agents are only in "
        "`registry.py`'s built-in list, which is used only when no entry point exists, so they never "
        "run and V&V › Review Gates reports MDR-EC-10 (debris compliance) as "
        "\"run the design loop first\" even after a run. The worksheets now point at the Orbit Trade "
        "Study columns and Export › Deorbit & Debris Compliance instead.")
    out = [INTRO.format(
        n_dec=len(cat["decisions"]), vocab=vocab, summary=summary, n_q=n_q,
        n_gap_before=before.get("gap", 0), n_gap_now=now.get("gap", 0),
        n_where=sum(1 for p in parts.values() if p.get("where")), n_dec_where=dec_where,
        n_reworded=len(reworded), n_links=len(links), checked=", ".join(checked),
        deferred=deferred_text)]

    out.append("\n## 1. Worksheet questions\n")
    out.append("Where = the logbook's \"Where in SpaceCDF\" links, in order. Book = sections of the open "
               "textbook. Before/Now = status (vocabulary above).\n")
    for w in wb["worksheets"]:
        out.append(f"\n### {w['id']} — {_md(w['title']['en'])}\n")
        out.append("| Part | Question | Before | Now | Where in SpaceCDF | Book | Gap | Fix |")
        out.append("|---|---|---|---|---|---|---|---|")
        for q in w["questions"]:
            key = f"{w['id']}/{q['id']}"
            p = parts.get(key) or {}
            qtext = _md(q["text"]["en"])
            pts = q.get("points") or []
            if pts and p.get("status") not in ("team", "ops"):
                qtext += f" ({len(pts)} sub-questions)"
            where = "; ".join(label(t) for t in p.get("where") or []) or "—"
            book = ", ".join(f"§{b}" if "." in str(b) else f"ch. {b}" for b in p.get("book") or []) or "—"
            fix = _md(p.get("fix") or "")
            if p.get("status") == "deferred":
                fix = (fix + " " if fix else "") + "Deferred: " + _md(p.get("reason"))
            if p.get("links"):
                fix = (fix + " " if fix else "") + "Links: " + ", ".join(p["links"]) + "."
            out.append(f"| {q['id']} | {qtext} | {p.get('before', '?')} | {p.get('status', '?')} | "
                       f"{where} | {book} | {_md(p.get('gap')) or '—'} | {fix or '—'} |")

    out.append("\n## 2. Catalogue decisions\n")
    out.append("Where comes from the decision's own entry in `where_map.yaml`, else from its workbook part. "
               "Capture = where the tool already offers \"Record decision\" at the point of decision.\n")
    out.append("| Decision | Gate | Seat | Part | Where in SpaceCDF | Capture | Links |")
    out.append("|---|---|---|---|---|---|---|")
    for d in cat["decisions"]:
        own = (wm.get("decisions") or {}).get(d["id"]) or {}
        part = d.get("part") or ""
        pe = parts.get(part) or {}
        where = own.get("where") or pe.get("where") or []
        src = "" if own.get("where") else " (from part)"
        lk = own.get("links") or pe.get("links") or []
        out.append(f"| {d['id']} | {d['gate'].upper()} | {d['seat']} | {part or 'none (CDR)'} | "
                   f"{'; '.join(label(t) for t in where) or '—'}{src if where else ''} | "
                   f"{', '.join(d.get('capture') or []) or '—'} | {', '.join(lk) or '—'} |")

    out.append("\n## 3. Screens that ask for input no worksheet prepares for\n")
    out.append("| Screen | Opens with | Prepared by | Status | Reason / note |")
    out.append("|---|---|---|---|---|")
    for r in wm.get("reverse") or []:
        out.append(f"| {_md(r['screen'])} | {label(r.get('target'))} | {_md(r.get('prepared_by'))} | "
                   f"{r.get('status')} | {_md(r.get('reason') or r.get('note') or '')} |")

    out.append("\n## 4. Link targets\n")
    out.append("What each \"Where in SpaceCDF\" link opens (checked against the frontend by "
               "`test_where_map.py`).\n")
    out.append("| Id | Label (EN) | Label (FR) | Opens |")
    out.append("|---|---|---|---|")
    for tid, t in targets.items():
        bits = []
        for k in ("wizard", "dialog", "vv", "level", "tab", "domain", "section", "anchor"):
            if t.get(k) is not None:
                bits.append(f"{k}={t[k]}")
        out.append(f"| `{tid}` | {_md(t['label']['en'])} | {_md(t['label']['fr'])} | {' '.join(bits)} |")
    return "\n".join(out) + "\n"


def render_links(wm: dict, wb: dict, cat: dict) -> str:
    links = wm.get("links") or {}
    used: dict[str, list[str]] = {k: [] for k in links}
    for key, p in (wm.get("parts") or {}).items():
        for lid in p.get("links") or []:
            used.setdefault(lid, []).append(key)
    for did, d in (wm.get("decisions") or {}).items():
        for lid in d.get("links") or []:
            used.setdefault(lid, []).append(did)
    out = ["# External links — SpaceCDF worksheets and decisions (Nov 2026)", "",
           "GENERATED by `design/scripts/gen_ws_audit.py` from the `links:` list of "
           "`design/configs/worksheets/where_map.yaml` — edit the map, then regenerate.", "",
           "Background reading the tool does not carry, shown under \"Read more\" next to a worksheet "
           "question or decision in the logbook. Rules: open-access pages from the agency, standards "
           "body, regulator or publisher (Wikipedia only when nothing better exists — none needed); "
           "`https://` only, on the host allow-list in `design/frontend/src/where/links.ts` (the "
           "server drops anything else too); opened in a new window with `target=\"_blank\" "
           "rel=\"noopener noreferrer\"`; the French URL in French where the publisher has one, else "
           "the English page with \"(en anglais)\" in its French title. Each URL was opened and its "
           "content checked on the date given.", "",
           "| Id | Title | URL | French URL | Why | Where used | Checked |",
           "|---|---|---|---|---|---|---|"]
    for lid, ln in links.items():
        out.append(f"| `{lid}` | {_md(ln['title']['en'])} | <{ln['url']}> | "
                   f"{'<' + ln['url_fr'] + '>' if ln.get('url_fr') else '—'} | {_md(ln.get('why'))} | "
                   f"{', '.join(used.get(lid) or []) or '—'} | {ln.get('checked')} |")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    wm, wb, cat = load()
    files = {AUDIT: render_audit(wm, wb, cat), LINKS: render_links(wm, wb, cat)}
    stale = 0
    for path, text in files.items():
        if args.check:
            cur = path.read_text(encoding="utf-8") if path.exists() else ""
            if cur != text:
                print(f"{path.relative_to(ROOT.parent)} is stale: run python3 scripts/gen_ws_audit.py", file=sys.stderr)
                stale += 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT.parent)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
